SPRITES = {}


def sprite(name, rows, **colours):
    """Registers a sprite: 16 rows of 16 palette characters, '.' transparent; colours override the palette."""
    rows = rows.split()
    assert len(rows) == 16, f'{name}: {len(rows)} rows'
    for index, row in enumerate(rows):
        assert len(row) == 16, f'{name}: row {index} has {len(row)} pixels: {row}'
    palette = dict(PALETTE)
    palette.update(colours)
    for row in rows:
        for char in row:
            assert char == '.' or char in palette, f'{name}: unknown colour {char!r}'
    SPRITES[name] = (rows, palette)


def render(name):
    rows, palette = SPRITES[name]
    image = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char != '.':
                colour = palette[char]
                image.putpixel((x, y), (int(colour[0:2], 16), int(colour[2:4], 16), int(colour[4:6], 16), 255))
    return image


